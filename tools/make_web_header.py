#!/usr/bin/env python3
"""
Pack the phone page into the firmware as a gzipped byte array.

    python3 tools/make_web_header.py           rewrite firmware/squidchrony/web_page.h
    python3 tools/make_web_header.py --check   fail if web_page.h is out of date (for CI)

The page links Google Fonts for the hosted demo. The chrono has no internet, so anything
between <!-- fonts:begin --> and <!-- fonts:end --> is dropped and the page uses the
phone's own fonts. Standard library only.
"""
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / "web" / "chrono-remote.html"
OUT = ROOT / "firmware" / "squidchrony" / "web_page.h"


def build():
    html = PAGE.read_text(encoding="utf-8")
    html, n = re.subn(r"<!-- fonts:begin -->.*?<!-- fonts:end -->\n?", "", html, flags=re.S)
    if n != 1:
        sys.exit("expected exactly one fonts:begin/fonts:end block in the page")
    raw = html.encode("utf-8")
    gz = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0: same input, same bytes
    rows = []
    for i in range(0, len(gz), 20):
        rows.append("    " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    text = (
        "// Generated by tools/make_web_header.py from web/chrono-remote.html -- do not edit.\n"
        f"// {len(raw)} bytes of HTML, {len(gz)} gzipped.\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "#ifndef PROGMEM\n"
        "#define PROGMEM\n"
        "#endif\n\n"
        "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n" + "\n".join(rows) + "\n};\n"
        "static const size_t WEB_PAGE_GZ_LEN = sizeof(WEB_PAGE_GZ);\n"
    )
    return text, len(raw), len(gz)


def main():
    text, raw_len, gz_len = build()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            sys.exit("web_page.h is out of date: run python3 tools/make_web_header.py")
        print(f"web_page.h is up to date ({gz_len} bytes)")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {raw_len} bytes of HTML, {gz_len} gzipped")


if __name__ == "__main__":
    main()
