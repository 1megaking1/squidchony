#!/usr/bin/env python3
"""
Design the decimation filter used by the firmware and write it as a C header.

The ADC samples the radar channel at 200 kS/s. The firmware low-pass filters and
keeps every 4th sample (50 kS/s). Anything between 30 and 50 kHz at the 200 kS/s
rate would fold into the 2-20 kHz band we measure, so the filter must stop it.

Usage:  python3 tools/design_fir.py      (rewrites firmware/squidchrony/fir_coeffs.h)
Only needs numpy.
"""
import pathlib
import numpy as np

FS = 200_000          # input rate, Hz
DECIM = 4
NTAPS = 64
PASS_HZ = 18_000      # 350 fps is about 17.2 kHz
STOP_HZ = 30_000      # first frequency that folds into our band after decimation
KAISER_BETA = 6.0

OUT = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "squidchrony" / "fir_coeffs.h"


def design():
    fc = (PASS_HZ + STOP_HZ) / 2 / FS                 # normalized cutoff (cycles/sample)
    n = np.arange(NTAPS) - (NTAPS - 1) / 2
    h = 2 * fc * np.sinc(2 * fc * n) * np.kaiser(NTAPS, KAISER_BETA)
    h /= h.sum()
    q = np.round(h * 32768).astype(int)
    q[NTAPS // 2] += 32768 - q.sum()                  # exact unity DC gain in Q15
    return q


def response(q):
    f = np.linspace(0, FS / 2, 4001)
    w = 2 * np.pi * f / FS
    H = np.abs(np.exp(-1j * np.outer(w, np.arange(NTAPS))) @ (q / 32768.0))
    db = 20 * np.log10(np.maximum(H, 1e-12))
    passband = db[f <= PASS_HZ]
    stopband = db[f >= STOP_HZ]
    return passband.min(), passband.max(), stopband.max(), f, db


def main():
    q = design()
    pmin, pmax, smax, f, db = response(q)
    at = lambda hz: db[np.argmin(abs(f - hz))]
    print(f"{NTAPS} taps, sum={q.sum()}  passband 0-{PASS_HZ/1000:.0f} kHz: {pmin:+.2f} to {pmax:+.2f} dB,"
          f"  stopband >= {STOP_HZ/1000:.0f} kHz: <= {smax:.1f} dB")
    print(f"  at 17.2 kHz (350 fps): {at(17_200):+.2f} dB   at 33 kHz: {at(33_000):.1f} dB")

    rows = []
    for i in range(0, NTAPS, 8):
        rows.append("    " + ", ".join(f"{v:6d}" for v in q[i:i + 8]) + ",")
    text = f"""// Generated by tools/design_fir.py -- do not edit by hand.
// Decimation low-pass for {FS // 1000} kS/s -> {FS // DECIM // 1000} kS/s, {NTAPS} taps, Q15 (sum = 32768).
// Passband 0-{PASS_HZ // 1000} kHz: {pmin:+.2f} to {pmax:+.2f} dB.  Stopband >= {STOP_HZ // 1000} kHz: <= {smax:.1f} dB.
#pragma once
#include <stdint.h>

namespace dsp {{
constexpr int FIR_TAPS = {NTAPS};
constexpr int FIR_DECIM = {DECIM};
static const int16_t FIR_COEFFS[FIR_TAPS] = {{
{chr(10).join(rows)}
}};
}}  // namespace dsp
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
